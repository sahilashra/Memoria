class BookGenerator:
    """
    Generates a Memory Bank from crawled repo data.
    Automatically handles large repos by chunking.
    """

    CHUNK_THRESHOLD = 60_000  # chars — above this, we chunk

    def __init__(self, config_path: str = "config.yaml"):
        self.model = ModelProvider(config_path)
        self.config_path = config_path

    def generate(
        self,
        repo_path: str,
        company_context: str,
        output_dir: str = "books",
        on_progress=None,
        content_type_override: Optional[str] = None,
    ) -> str:
        """
        Full pipeline: crawl → generate → save → return output path.
        on_progress: optional callback(step: str) for UI updates.
        """

        def progress(msg):
            if on_progress:
                on_progress(msg)

        # Step 1: Crawl
        # Pick a pre-crawl label based on whether the path looks like a doc folder
        _p = Path(repo_path)
        _pre_label = "Reading files..." if _p.is_dir() and not any(
            (_p / sig).exists() for sig in (
                "package.json", "requirements.txt", "setup.py", "pyproject.toml",
                "Cargo.toml", "go.mod", "Makefile", "Dockerfile", ".git"
            )
        ) else "Crawling repository..."
        progress(_pre_label)
        crawler = RepoCrawler(repo_path, self.config_path)
        data = crawler.crawl()

        project_name = data["name"]
        structure = data["structure"]
        files = data["files"]

        # Detect content type now that we have the file list
        content_type = content_type_override or _detect_content_type(files)
        _action = {
            "audio":    "Transcribing audio",
            "video":    "Analysing video (frames + audio)",
            "image":    "Analysing image",
            "document": "Extracting documents",
            "notebook": "Reading notebook",
            "process":  "Extracting process / SOP",
        }.get(content_type, "Analysing")

        # Step 2: Build file content string
        files_content = self._format_files(files)
        total_chars = len(files_content)

        # Step 3: Generate book (single pass or chunked)
        if total_chars <= self.CHUNK_THRESHOLD:
            progress(f"{_action} ({data['stats']['total_files']} file(s))...")
            book_content = self._generate_single(
                project_name, company_context, structure, files_content, files
            )
        else:
            progress(f"Large collection ({total_chars // 1000}K chars). Processing in chunks...")
            book_content = self._generate_chunked(
                project_name, company_context, structure, crawler, on_progress, files
            )

        # Step 3.5: Inject content type into the metadata header line so the UI
        # can display the correct badge without heuristics.
        import re as _re
        _type_tag = {
            "audio":       "audio",
            "video":       "video",
            "image":       "image",
            "document":    "docs",
            "notebook":    "notebook",
            "mixed":       "mixed",
            "spreadsheet": "sheet",
            "process":     "process",
        }.get(content_type, "code")
        book_content = _re.sub(
            r"(\| Generated by Memoria \([^)]+\))",
            rf"\1 | Type: {_type_tag}",
            book_content,
            count=1,
        )

        # Step 4: Save
        progress("Saving memory bank...")
        output_path = self._save_book(project_name, book_content, output_dir)

        # Record metadata so Update from UI knows the source path
        try:
            from .meta import record as _meta_record
            _meta_record(project_name, repo_path, company_context)
        except Exception:
            pass  # metadata recording is best-effort, never block

        return output_path

    def generate_from_text(
        self,
        source_name: str,
        company_context: str,
        content: str,
        output_dir: str = "books",
        on_progress=None,
    ) -> str:
        """
        Generate a Memory Bank from raw text — used by `memoria pull`.
        Bypasses the crawler entirely; content is provided directly (e.g. from an MCP source).
        Automatically chunks large content the same way the crawler-based path does.
        """
        def progress(msg):
            if on_progress:
                on_progress(msg)

        project_name = source_name
        structure = f"[Content pulled from external source: {source_name}]"

        # Treat all MCP-pulled content as a document collection
        # (a synthetic single-file dict so _detect_content_type → 'document')
        files = {f"{source_name}.md": content}

        total_chars = len(content)

        if total_chars <= self.CHUNK_THRESHOLD:
            progress(f"Generating memory bank ({total_chars // 1000}K chars)...")
            book_content = self._generate_single(
                project_name, company_context, structure, content, files
            )
        else:
            # Split into CHUNK_THRESHOLD-sized chunks and summarize each, then synthesize
            progress(f"Large content ({total_chars // 1000}K chars). Processing in chunks...")
            raw_chunks = [
                content[i: i + self.CHUNK_THRESHOLD]
                for i in range(0, total_chars, self.CHUNK_THRESHOLD)
            ]
            summaries: list[str] = []
            consecutive_rl = 0
            for i, chunk in enumerate(raw_chunks):
                progress(f"Processing chunk {i + 1} of {len(raw_chunks)}...")
                for attempt in range(2):  # original + 1 retry
                    try:
                        summary = self.model.complete(
                            DOCUMENT_SYSTEM_PROMPT,
                            DOCUMENT_CHUNK_SUMMARY_PROMPT.format(files_content=chunk),
                        )
                        summaries.append(f"--- Chunk {i + 1} ---\n{summary}")
                        consecutive_rl = 0
                        break
                    except RuntimeError as e:
                        if str(e).startswith("[AUTH]"):
                            raise  # never retry auth failures
                        if "[RATELIMIT]" in str(e) or "[TRANSIENT]" in str(e):
                            consecutive_rl += 1
                            if consecutive_rl >= 3:
                                raise RuntimeError(
                                    "Rate limit hit 3 times in a row. "
                                    "Your API quota may be exhausted. "
                                    "Wait a few minutes, check your quota, or switch model."
                                ) from e
                            wait = 15 * (attempt + 1)
                            progress(
                                f"Rate limit hit ({consecutive_rl}/3). "
                                f"Waiting {wait}s before retry…"
                            )
                            time.sleep(wait)
                            if attempt == 1:
                                raise
                        else:
                            raise
                if i < len(raw_chunks) - 1:
                    time.sleep(2)

            progress("Synthesizing final memory bank...")
            book_content = self._call_with_retry(
                DOCUMENT_SYSTEM_PROMPT,
                DOCUMENT_SYNTHESIS_PROMPT.format(
                    project_name=project_name,
                    company_context=company_context,
                    summaries="\n\n".join(summaries),
                    date=datetime.now().strftime("%Y-%m-%d"),
                    model=self.model.model,
                ),
            )

        # Inject type tag: MCP-pulled content is always treated as 'mcp'
        import re as _re2
        book_content = _re2.sub(
            r"(\| Generated by Memoria \([^)]+\))",
            r"\1 | Type: mcp",
            book_content,
            count=1,
        )

        progress("Saving memory bank...")
        return self._save_book(project_name, book_content, output_dir)

    def _generate_single(
        self, project_name: str, company_context: str, structure: str,
        files_content: str, files: dict = None
    ) -> str:
        """Single model call — picks the right prompt based on content type."""
        content_type = _detect_content_type(files or {})
        date = datetime.now().strftime("%Y-%m-%d")

        template_args = dict(
            project_name=project_name,
            company_context=company_context,
            files_content=files_content,
            date=date,
            model=self.model.model,
        )

        if content_type in ("audio", "video"):
            return self.model.complete(
                AUDIO_SYSTEM_PROMPT,
                AUDIO_PROMPT_TEMPLATE.format(**template_args),
            )
        elif content_type in ("document", "image"):
            return self.model.complete(
                DOCUMENT_SYSTEM_PROMPT,
                DOCUMENT_PROMPT_TEMPLATE.format(**template_args),
            )
        elif content_type == "notebook":
            return self.model.complete(
                NOTEBOOK_SYSTEM_PROMPT,
                NOTEBOOK_PROMPT_TEMPLATE.format(**template_args),
            )
        elif content_type == "process":
            return self.model.complete(
                PROCESS_SYSTEM_PROMPT,
                PROCESS_PROMPT_TEMPLATE.format(**template_args),
            )
        else:
            # Code / mixed — original behaviour
            prompt = BOOK_PROMPT_TEMPLATE.format(
                structure=structure, **template_args
            )
            return self.model.complete(SYSTEM_PROMPT, prompt)

    def _generate_chunked(
        self, project_name: str, company_context: str, structure: str,
        crawler: RepoCrawler, on_progress=None, files: dict = None
    ) -> str:
        """Multi-pass generation for large repos/collections — prompts adapt to content type."""
        content_type = _detect_content_type(files or {})
        is_doc     = content_type in ("document", "audio", "video", "notebook", "image")
        is_process = content_type == "process"

        if is_process:
            chunk_system   = PROCESS_SYSTEM_PROMPT
            chunk_prompt   = PROCESS_CHUNK_SUMMARY_PROMPT
            synth_system   = PROCESS_SYSTEM_PROMPT
            synth_template = PROCESS_SYNTHESIS_PROMPT
        elif is_doc:
            chunk_system   = DOCUMENT_SYSTEM_PROMPT
            chunk_prompt   = DOCUMENT_CHUNK_SUMMARY_PROMPT
            synth_system   = DOCUMENT_SYSTEM_PROMPT
            synth_template = DOCUMENT_SYNTHESIS_PROMPT
        else:
            chunk_system   = SYSTEM_PROMPT
            chunk_prompt   = CHUNK_SUMMARY_PROMPT
            synth_system   = SYSTEM_PROMPT
            synth_template = SYNTHESIS_PROMPT

        chunks = crawler.get_chunked_files()
        summaries = []
        consecutive_rl = 0  # consecutive rate-limit failures across chunks

        for i, chunk in enumerate(chunks):
            if on_progress:
                on_progress(f"Processing chunk {i + 1} of {len(chunks)}...")

            files_content = self._format_files(chunk)

            for attempt in range(2):  # max 2 attempts: original + 1 retry
                try:
                    summary = self.model.complete(
                        chunk_system,
                        chunk_prompt.format(files_content=files_content),
                    )
                    summaries.append(f"--- Chunk {i + 1} ---\n{summary}")
                    consecutive_rl = 0  # reset on success
                    break
                except RuntimeError as e:
                    if "429" in str(e) or "rate" in str(e).lower() or "quota" in str(e).lower():
                        consecutive_rl += 1
                        if consecutive_rl >= 3:
                            raise RuntimeError(
                                "Rate limit hit 3 times in a row. "
                                "Your API quota may be exhausted. "
                                "Wait a few minutes, check your quota, or switch model."
                            ) from e
                        wait = 15 * (attempt + 1)   # 15s then 30s
                        if on_progress:
                            on_progress(
                                f"Rate limit hit ({consecutive_rl}/3). "
                                f"Waiting {wait}s before retry…"
                            )
                        time.sleep(wait)
                        if attempt == 1:
                            raise
                    else:
                        raise

            if i < len(chunks) - 1:
                time.sleep(2)

        if on_progress:
            on_progress("Synthesizing final memory bank...")

        synthesis_prompt = synth_template.format(
            project_name=project_name,
            company_context=company_context,
            structure=structure,
            summaries="\n\n".join(summaries),
            date=datetime.now().strftime("%Y-%m-%d"),
            model=self.model.model,
        )
        for attempt in range(2):  # max 2 attempts: original + 1 retry
            try:
                return self.model.complete(synth_system, synthesis_prompt)
            except RuntimeError as e:
                err = str(e)
                if any(x in err for x in ["503", "502", "unavailable", "connection", "disconnected"]):
                    wait = 15 * (attempt + 1)
                    if on_progress:
                        on_progress(f"Model temporarily unavailable. Retrying in {wait}s…")
                    time.sleep(wait)
                    if attempt == 1:
                        raise
                else:
                    raise

    def _format_files(self, files: dict) -> str:
        """Format file dict into a readable string for the model."""
        parts = []
        for path, data in files.items():
            parts.append(f"### {path}\n```\n{data['content']}\n```")
        return "\n\n".join(parts)

    def _save_book(self, project_name: str, content: str, output_dir: str) -> str:
        """
        Save the generated book — one file per project.

        Behaviour:
        - One canonical file: {project}_memory_bank.md
        - Before overwriting, the previous version moves to .archive/
        - Archive files older than ARCHIVE_TTL_DAYS are auto-purged (recycle bin)
        """
        ARCHIVE_TTL_DAYS = 30

        books_path = Path(output_dir)
        books_path.mkdir(parents=True, exist_ok=True)

        archive_path = books_path / ".archive"
        archive_path.mkdir(exist_ok=True)

        safe_name = "".join(c if c.isalnum() or c in "-_" else "_" for c in project_name)
        book_file = books_path / f"{safe_name}_memory_bank.md"

        # ── Archive previous version before overwriting ──
        if book_file.exists():
            prev_modified = datetime.fromtimestamp(book_file.stat().st_mtime)
            archive_name = f"{safe_name}_{prev_modified.strftime('%Y%m%d_%H%M%S')}.md"
            archive_target = archive_path / archive_name
            # Handle sub-second collisions (e.g. rapid saves in tests or loops)
            counter = 1
            while archive_target.exists():
                archive_target = archive_path / (
                    f"{safe_name}_{prev_modified.strftime('%Y%m%d_%H%M%S')}_{counter}.md"
                )
                counter += 1
            book_file.rename(archive_target)

        # ── Enforce correct header (AI sometimes overwrites it) ──
        content = self._enforce_header(content, project_name)

        # ── Write new book (single file, timestamp inside content) ──
        book_file.write_text(content, encoding="utf-8")

        # ── Auto-index into vector search ──
        try:
            from .search import index_book
            index_book(safe_name, content, output_dir)
        except Exception:
            pass  # Search indexing is best-effort, never block the main flow

        # ── Audit ──
        try:
            from .audit import log_action as _audit
            _audit("generate_book", target=project_name, config_path=self.config_path)
        except Exception:
            pass

        # ── Purge archive files older than TTL (recycle bin behaviour) ──
        self._purge_old_archives(archive_path, ARCHIVE_TTL_DAYS)

        return str(book_file)

    def _purge_old_archives(self, archive_path: Path, ttl_days: int):
        """Delete archive files older than ttl_days. Silent — never blocks the user."""
        try:
            cutoff = datetime.now().timestamp() - (ttl_days * 86400)
            for old_file in archive_path.glob("*.md"):
                if old_file.stat().st_mtime < cutoff:
                    old_file.unlink()
        except Exception:
            pass  # Archive cleanup is best-effort, never crash the main flow

