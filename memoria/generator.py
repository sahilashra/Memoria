# ── Content-type detection ────────────────────────────────────────────────────

CODE_EXTENSIONS = {
    ".py", ".js", ".ts", ".tsx", ".jsx", ".go", ".java", ".rb", ".rs",
    ".cpp", ".c", ".cs", ".php", ".swift", ".kt", ".scala", ".sh", ".bash",
    ".sql", ".html", ".css", ".scss", ".vue", ".svelte",
}
AUDIO_EXTENSIONS  = {".mp3", ".m4a", ".wav"}
VIDEO_EXTENSIONS  = {".mp4", ".mov", ".avi", ".mkv", ".webm"}
IMAGE_EXTENSIONS  = {".png", ".jpg", ".jpeg", ".gif", ".webp", ".bmp"}
DOC_EXTENSIONS    = {".pdf", ".docx", ".doc", ".pptx", ".ppt", ".xlsx", ".xls", ".csv"}
NOTEBOOK_EXTENSIONS = {".ipynb"}
WEB_EXTENSIONS    = {".html", ".htm"}

# Filename stems (lowercased, dashes/underscores stripped) that suggest a process/SOP doc
PROCESS_FILENAME_KEYWORDS = {
    "sop", "runbook", "procedure", "procedures", "workflow", "workflows",
    "playbook", "playbooks", "checklist", "checklists", "policy", "policies",
    "escalation", "process", "processes", "protocol", "protocols", "standard",
    "howto", "how-to", "guide", "guidelines", "onboarding", "offboarding",
    "incident", "oncall", "on-call", "deployment", "rollback", "release",
    "triage", "response", "postmortem", "post-mortem", "runsheet",
}


def _detect_content_type(files: dict) -> str:
    """
    Classify a file collection as: 'code', 'audio', 'video', 'document',
    'notebook', 'process', or 'mixed'.
    Used to pick the right generation prompt and progress messages.
    """
    exts = {Path(p).suffix.lower() for p in files}
    has_code     = bool(exts & CODE_EXTENSIONS)
    has_audio    = bool(exts & AUDIO_EXTENSIONS)
    has_video    = bool(exts & VIDEO_EXTENSIONS)
    has_docs     = bool(exts & (DOC_EXTENSIONS | IMAGE_EXTENSIONS | WEB_EXTENSIONS))
    has_notebook = bool(exts & NOTEBOOK_EXTENSIONS)
    has_text     = bool(exts & {".md", ".txt", ".rst"})

    # Single video file (audio + visual frames)
    if has_video and len(files) == 1:
        return "video"
    # Single audio file
    if has_audio and len(files) == 1:
        return "audio"
    # Single image
    if (exts & IMAGE_EXTENSIONS) and len(files) == 1:
        return "image"
    # Notebooks (possibly with some docs)
    if has_notebook and not has_code:
        return "notebook"
    # Process / SOP detection — filename heuristics (before general document check)
    # Applies when there's no code and content is docs/markdown/text
    if not has_code and (has_docs or has_text):
        for fpath in files:
            stem = Path(fpath).stem.lower().replace("-", " ").replace("_", " ")
            words = set(stem.split())
            if words & PROCESS_FILENAME_KEYWORDS:
                return "process"
        # Also scan first ~500 chars of each file for strong process signals
        _process_signals = {
            "step 1", "step 2", "step one", "trigger:", "escalate to",
            "decision point", "prerequisites:", "runbook", "playbook",
            "standard operating procedure", "sop:", "procedure:", "workflow:",
        }
        for _fdata in files.values():
            # _fdata may be a dict {"content": "..."} or a plain string
            _raw = _fdata.get("content", "") if isinstance(_fdata, dict) else _fdata
            _snippet = str(_raw)[:500].lower()
            if any(sig in _snippet for sig in _process_signals):
                return "process"
    # Document collection with no code
    if has_docs and not has_code:
        return "document"
    # Plain-text / markdown collection (no code, no office docs) — treat as document
    if has_text and not has_code and not has_docs:
        return "document"
    # Default: treat as code / mixed
    return "code"


