@dataclass
class ServerInfo:
    base_url: str
    books_dir: Path


@pytest.fixture(scope="session")
def live_server(books_dir, config_file) -> Generator[ServerInfo, None, None]:
    """
    Start a real uvicorn server for the duration of the E2E test session.
    Yields a ServerInfo(base_url, books_dir).
    """
    import socket
    import uvicorn

    with socket.socket() as s:
        s.bind(("127.0.0.1", 0))
        port = s.getsockname()[1]

    from memoria.ui import create_app
    app = create_app(
        config_path=str(config_file),
        books_dir=str(books_dir),
    )

    server = uvicorn.Server(uvicorn.Config(
        app=app,
        host="127.0.0.1",
        port=port,
        log_level="error",
    ))

    thread = threading.Thread(target=server.run, daemon=True)

    with patch("litellm.completion", side_effect=_mock_completion):
        thread.start()
        base_url = f"http://127.0.0.1:{port}"
        for _ in range(30):
            try:
                import urllib.request
                urllib.request.urlopen(f"{base_url}/api/projects", timeout=1)
                break
            except Exception:
                time.sleep(0.2)
        else:
            pytest.fail("E2E test server did not start within 6 seconds")

        yield ServerInfo(base_url=base_url, books_dir=books_dir)

        server.should_exit = True
        thread.join(timeout=5)


@pytest.fixture
def http_client(live_server) -> httpx.AsyncClient:
    """Async HTTP client pointed at the live server (test-scoped)."""
    return httpx.AsyncClient(base_url=live_server.base_url, timeout=30.0)


# ── SSE helpers ────────────────────────────────────────────────────────────────

def parse_sse_events(raw: str) -> list[dict]:
    """
    Parse raw SSE text into a list of decoded JSON objects.

    Handles both formats:
      • data: {"type": "done", ...}           — type is in the JSON payload
      • event: done\\ndata: {"message": "..."}  — type is in the SSE event field

    In the second format the event name is injected as {"type": <event_name>}
    into the returned dict so callers can uniformly check e.get("type").

    Input  : "data: {...}\\n\\ndata: {...}\\n\\n"
    Output : [{...}, {...}]
    """
    events = []
    for block in raw.split("\n\n"):
        block = block.strip()
        if not block:
            continue
        event_name: str | None = None
        data_payload: str | None = None
        for line in block.splitlines():
            if line.startswith("event:"):
                event_name = line[len("event:"):].strip()
            elif line.startswith("data:"):
                data_payload = line[len("data:"):].strip()
        if data_payload:
            try:
                obj = json.loads(data_payload)
                # If the SSE `event:` field was set and the payload has no `type`
                # key, inject the event name so tests can check e.get("type").
                if event_name and "type" not in obj:
                    obj["type"] = event_name
                events.append(obj)
            except json.JSONDecodeError:
                pass
    return events
