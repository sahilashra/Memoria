"""
E2E test conftest for Memoria.

Strategy
────────
Each test session spins up a real uvicorn server against a temp books_dir
pre-seeded with two small Memory Bank .md files and a tiny sample_project/
directory. litellm.completion is monkeypatched to return deterministic
streaming SSE responses so no API keys are needed.

The ChromaDB index is built from the seeded books at session start so
semantic search works out-of-the-box.

Fixtures
────────
  books_dir          — temp dir pre-seeded with 2 Memory Banks
  sample_project_dir — 3 small Python files that can be analyzed
  config_file        — minimal config.yaml
  live_server        — real uvicorn on a random port; yields base URL + books_dir
  http_client        — httpx.AsyncClient pointed at the live server

Usage
─────
  pytest tests/e2e/                 # run all e2e tests
  pytest tests/e2e/ -k test_chat    # run one file
  pytest tests/e2e/ -v              # verbose

Requirements
────────────
  pip install -r requirements-dev.txt
"""

