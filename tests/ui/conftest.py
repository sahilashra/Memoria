# ── Helpers ───────────────────────────────────────────────────────────────────

def wait_for_stream_done(page, selector: str, timeout: int = 15_000) -> str:
    """
    Wait until the element at `selector` stops changing content,
    indicating streaming has finished. Returns the final text content.

    Uses a polling loop: checks content every 300ms; exits when stable
    for 600ms or when timeout is reached.
    """
    import time as _time

    deadline = _time.time() + timeout / 1000
    last_text = ""
    stable_count = 0

    while _time.time() < deadline:
        try:
            current = page.locator(selector).inner_text()
        except Exception:
            current = ""
        if current == last_text and current:
            stable_count += 1
            if stable_count >= 2:   # stable for ~600ms
                return current
        else:
            stable_count = 0
        last_text = current
        _time.sleep(0.3)

    return last_text  # return whatever we have at timeout


def click_project(page, project_name: str):
    """Click a project in the sidebar by name (case-insensitive prefix match)."""
    page.locator(f".project-item[data-project]").filter(
        has_text=project_name
    ).first.click()


def switch_tab(page, tab_name: str):
    """Click a tab button by its data-tab attribute."""
    page.locator(f".tab[data-tab='{tab_name}']").click()
