# ── Skip guard ────────────────────────────────────────────────────────────────

def pytest_addoption(parser):
    parser.addoption(
        "--run-ui",
        action="store_true",
        default=False,
        help="Run Playwright UI tests (requires: pip install playwright; playwright install chromium)",
    )


def pytest_collection_modifyitems(config, items):
    if not config.getoption("--run-ui"):
        skip = pytest.mark.skip(reason="Pass --run-ui to run Playwright tests")
        for item in items:
            if "tests/ui" in str(item.fspath) or "tests\\ui" in str(item.fspath):
                item.add_marker(skip)


