@pytest.fixture(scope="session")
def live_server(books_dir, config_file) -> Generator[str, None, None]:
    """
    Start a real uvicorn server for the duration of the test session.
    Yields the base URL (e.g. 'http://localhost:34521').
    """
    import socket
    import uvicorn

    # Find a free port
    with socket.socket() as s:
        s.bind(("127.0.0.1", 0))
        port = s.getsockname()[1]

    from memoria.ui import create_app
    app = create_app(
        config_path=str(config_file),
        books_dir=str(books_dir),
    )

    server = uvicorn.Server(uvicorn.Config(
        app=app,
        host="127.0.0.1",
        port=port,
        log_level="error",  # suppress uvicorn logs during tests
    ))

    thread = threading.Thread(target=server.run, daemon=True)

    with patch("litellm.completion", side_effect=_mock_completion):
        thread.start()
        # Wait for server to be ready
        base_url = f"http://127.0.0.1:{port}"
        for _ in range(30):
            try:
                import urllib.request
                urllib.request.urlopen(f"{base_url}/api/projects", timeout=1)
                break
            except Exception:
                time.sleep(0.2)
        else:
            pytest.fail("Test server did not start within 6 seconds")

        yield base_url

        server.should_exit = True
        thread.join(timeout=5)


