"""
Playwright conftest for Memoria UI tests.

Strategy
────────
Each test session spins up a real uvicorn server against a temp books_dir
with pre-seeded Memory Bank files. litellm.completion is monkeypatched at
the module level to return deterministic streaming SSE responses, so no
API keys are required.

Fixtures
────────
  live_server   — starts uvicorn on a random port; yields base URL
  page          — Playwright Page object navigated to the UI URL
  books_dir     — temp directory pre-seeded with 2 Memory Bank files
  mock_llm      — patches litellm.completion for all UI test SSE calls

Usage
─────
  pytest tests/ui/ --headed              # see the browser
  pytest tests/ui/ -k test_chat          # run one file
  pytest tests/ui/ --slowmo 200          # slow down interactions

Requirements
────────────
  pip install -r requirements-dev.txt
  playwright install chromium

Note
────
These tests are skipped automatically if playwright is not installed.
Enable them by running:  pytest tests/ui/ --run-ui
(configured via the --run-ui flag registered below)
"""

import json
