def _make_streaming_mock(text: str):
    """Return a mock litellm completion that streams the given text word by word."""
    words = text.split(" ")
    chunks = []
    for word in words:
        c = MagicMock()
        c.choices[0].delta.content = word + " "
        chunks.append(c)
    # Final chunk with None content
    final = MagicMock()
    final.choices[0].delta.content = None
    chunks.append(final)
    return chunks


def _mock_completion(*args, **kwargs):
    """Universal mock: detects stream=True and returns appropriate mock."""
    is_stream = kwargs.get("stream", False)
    messages  = kwargs.get("messages", [])

    # Pick a response based on the last user message content
    user_content = ""
    for m in reversed(messages):
        if m.get("role") == "user":
            user_content = m.get("content", "").lower()
            break

    if "oauth" in user_content or "auth" in user_content:
        text = "The auth-service uses OAuth2 and JWT tokens. Rate limit is 100 req/s."
    elif "payment" in user_content or "stripe" in user_content:
        text = "Payments go through Stripe. PostgreSQL stores transaction records."
    elif "plan" in user_content:
        text = json.dumps({
            "summary": "Plan touches auth-service and payments-service.",
            "affected_projects": ["auth-service", "payments-service"],
            "dependencies": [
                {"project": "auth-service", "relation": "OAuth2 tokens", "notes": "rate limit concern"}
            ],
            "risks": [
                {"severity": "high", "title": "Rate limit", "detail": "100 req/s cap", "source": "auth-service"}
            ],
            "prior_art": [],
            "recommended_actions": ["Run memoria ask --project auth-service"],
        })
    else:
        text = "This project uses Python and FastAPI. See the Memory Bank for full details."

    if is_stream:
        return _make_streaming_mock(text)
    else:
        mock = MagicMock()
        mock.choices[0].message.content = text
        return mock


